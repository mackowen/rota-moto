'use strict';
const assert=require('node:assert/strict');
global.RotaMotoNavigation=require('../navigation-intents');
const workflow=require('../navigation-workflow');
const stops=Array.from({length:7},(_,index)=>({id:`delivery-${index+1}`,latitude:-23.5+index/1000,longitude:-46.6,label:`Synthetic ${index+1}`}));
const google=workflow.createBatches(stops,'google',4);
assert.deepEqual(google.batches.map(batch=>batch.map(stop=>stop.id)),[['delivery-1','delivery-2','delivery-3','delivery-4'],['delivery-5','delivery-6','delivery-7']]);
assert.equal(workflow.createBatches(stops,'google',99).batchSize,4,'Google size has a defensive adapter clamp');
assert.deepEqual(workflow.createBatches(stops,'waze').batches.map(batch=>batch.length),[1,1,1,1,1,1,1]);
assert.deepEqual(workflow.createBatches(stops,'osmand').batches.map(batch=>batch.length),[1,1,1,1,1,1,1]);
assert.match(workflow.buildUrl(stops.slice(0,4),'google',4),/google\.com\/maps\/dir/u);
assert.match(workflow.buildUrl(stops.slice(0,1),'waze'),/waze\.com\/ul/u);
assert.match(workflow.buildUrl(stops.slice(0,1),'osmand'),/^geo:0,0\?q=/u,'OsmAnd retains the proven Android geo deep link');
assert.throws(()=>workflow.buildUrl(stops,'waze'),/one stop/u);
assert.doesNotMatch(workflow.buildUrl(stops.slice(0,1),'google'),/Synthetic|delivery-1/u,'external navigation contains coordinates only, not labels or customer identifiers');
const route={routeId:'route-synthetic',revision:8,sequence:stops.map(stop=>stop.id)};
let progress=workflow.createProgress(route,'google',4,100);
assert.equal(workflow.currentBatch(progress,stops,'google',4).batchIndex,0);
progress=workflow.markOpened(progress,110);
assert.equal(progress.status,'opened');
progress=workflow.markBatchNavigated(progress,stops,'google',4,120);
assert.equal(progress.cursorDeliveryId,'delivery-5');
assert.equal(progress.status,'ready','marking navigation batch never means delivery completed');
assert.equal(workflow.currentBatch(progress,stops,'google',4).batchIndex,1);
progress=workflow.markOpened(progress,130);
progress=workflow.markBatchNavigated(progress,stops,'google',4,140);
assert.equal(progress.status,'all_visited');
assert.equal(progress.cursorDeliveryId,null);
assert.equal(workflow.currentBatch(progress,stops,'google',4).batch,null);
const reloaded=structuredClone(progress);
assert.equal(reloaded.status,'all_visited','progress is serializable for IndexedDB persistence');
const revised={routeId:'route-synthetic',revision:9,sequence:['delivery-1','delivery-2','delivery-5','delivery-6','delivery-7','delivery-8']};
assert.equal(workflow.isStale(progress,revised),true,'new Route revision requires reconciliation');
const rebased=workflow.rebaseProgress({...progress,cursorDeliveryId:'delivery-5'},revised,'waze',4,150);
assert.equal(rebased.cursorDeliveryId,'delivery-5');
assert.equal(workflow.isStale(rebased,revised),false);
assert.equal(workflow.currentBatch(rebased,stops.filter(stop=>revised.sequence.includes(stop.id)),'waze').batch[0].id,'delivery-5');
assert.throws(()=>workflow.createBatches([{id:'bad',latitude:91,longitude:0}],'google'),/valid coordinates/u);
assert.throws(()=>workflow.createBatches([{id:'same',latitude:0,longitude:0},{id:'same',latitude:0,longitude:0}],'google'),/unique identifiers/u);
assert.throws(()=>workflow.markBatchNavigated(workflow.createProgress(route),stops),/Open/u);
assert.throws(()=>workflow.createBatches(stops,'unknown'),/Unsupported/u);
console.log('Persistent route navigation workflow, batching, revision reconciliation and provider boundaries: PASS');
